            (f"{t}-এর একটি উদাহরণ দিয়ে ব্যাখ্যা কর।", f"{fa}। বাস্তব উদাহরণ হিসেবে দৈনন্দিন জীবন/প্রকৃতিতে এর প্রয়োগ লক্ষ্য করা যায়।",3),
